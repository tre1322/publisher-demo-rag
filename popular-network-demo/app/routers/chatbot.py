"""Consumer Chatbot Preview router — Phase F.3.

Endpoints:
    GET    /api/chatbot                          slice for ChatbotPreviewView
    GET    /api/chatbot/conversations            list w/ filters (sentiment, escalation, search)
    GET    /api/chatbot/conversations/{id}       full transcript for a single session
    POST   /api/chatbot/seed-fixtures            populate sample fixture conversations
    DELETE /api/chatbot/fixtures                 wipe seeded fixture rows

Read-only from the dashboard side. Conversation rows are generated by the
real consumer-facing chatbot (out of scope for this demo — rows are seeded
fixture-style so the dashboard surface has something to render).

Tier gating: dashboard hides the sidebar tab for tier < 3, but the endpoints
still return data so the upsell card can show the empty-state preview. The
real (downstream) chatbot enforces its own per-tier gating.
"""
from __future__ import annotations

from datetime import datetime, timedelta
from typing import Any, Literal, Optional

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session

from ..db import get_db
from ..models import Business, ChatbotConversation

router = APIRouter()


SENTIMENT_LABELS: dict[str, str] = {
    "positive": "Positive",
    "neutral":  "Neutral",
    "negative": "Negative",
    "mixed":    "Mixed",
}


# ---------------------------------------------------------------------------
# Payload shapers
# ---------------------------------------------------------------------------

def conversation_summary(c: ChatbotConversation) -> dict[str, Any]:
    """List-card payload — omits the full transcript (which can be long)."""
    return {
        "id":              c.id,
        "externalId":      c.external_id,
        "consumerLabel":   c.consumer_label,
        "topicLabel":      c.topic_label,
        "sentiment":       c.sentiment,
        "sentimentLabel":  SENTIMENT_LABELS.get(c.sentiment, c.sentiment),
        "escalationFlag":  c.escalation_flag,
        "escalationReason": c.escalation_reason,
        "turnCount":       c.turn_count,
        "durationSeconds": c.duration_seconds,
        "startedAt":       c.started_at.isoformat() if c.started_at else None,
        "endedAt":         c.ended_at.isoformat() if c.ended_at else None,
        "referrerLabel":   c.referrer_label,
    }


def conversation_full(c: ChatbotConversation) -> dict[str, Any]:
    """Detail payload — includes the transcript."""
    return {
        **conversation_summary(c),
        "transcript": c.transcript_json or [],
    }


