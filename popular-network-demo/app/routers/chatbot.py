@router.get("/chatbot")
def get_chatbot(business_id: int = 1, db: Session = Depends(get_db)) -> dict[str, Any]:
    biz = db.get(Business, business_id)
    if biz is None:
        raise HTTPException(status_code=404, detail=f"business {business_id} not found")

    conversations = (
        db.query(ChatbotConversation)
        .filter(ChatbotConversation.business_id == business_id)
        .order_by(ChatbotConversation.started_at.desc(), ChatbotConversation.id.desc())
        .limit(50)
        .all()
    )

    total          = len(conversations)
    escalation_ct  = sum(1 for c in conversations if c.escalation_flag)
    sentiment_ct: dict[str, int] = {"positive": 0, "neutral": 0, "negative": 0, "mixed": 0}
    for c in conversations:
        sentiment_ct[c.sentiment] = sentiment_ct.get(c.sentiment, 0) + 1
    avg_turns      = (sum(c.turn_count for c in conversations) / total) if total else 0.0
    avg_duration_s = (sum(c.duration_seconds for c in conversations) / total) if total else 0.0

    # Top recurring topic labels (frequency-sorted, top 6). Topic strings are
    # already short headlines per session so a string-equality groupby works
    # without LLM clustering. When the real chatbot is wired, we can replace
    # this with a proper topic-clustering pipeline.
    topic_counts: dict[str, int] = {}
    for c in conversations:
        topic_counts[c.topic_label] = topic_counts.get(c.topic_label, 0) + 1
    top_topics = sorted(
        [{"label": k, "count": v} for k, v in topic_counts.items()],
        key=lambda t: t["count"],
        reverse=True,
    )[:6]

    return {
        "tier":              biz.tier,
        "tierEligible":      biz.tier >= 3,
        "conversations":     [conversation_summary(c) for c in conversations],
        "totals": {
            "count":            total,
            "escalationCount":  escalation_ct,
            "sentimentCounts":  sentiment_ct,
            "avgTurns":         avg_turns,
            "avgDurationSecs":  avg_duration_s,
        },
        "topTopics":        top_topics,
        "hasAnyConversation": total > 0,
    }


@router.get("/chatbot/conversations")
def list_conversations(
    business_id: int = 1,
    sentiment: Optional[str] = Query(None, description="positive|neutral|negative|mixed"),
    escalation_only: bool = Query(False),
    search: Optional[str] = Query(None, max_length=200),
    limit: int = Query(50, ge=1, le=200),
    db: Session = Depends(get_db),
) -> list[dict[str, Any]]:
    q = db.query(ChatbotConversation).filter(ChatbotConversation.business_id == business_id)
    if sentiment:
        q = q.filter(ChatbotConversation.sentiment == sentiment)
    if escalation_only:
        q = q.filter(ChatbotConversation.escalation_flag.is_(True))
    if search:
        q = q.filter(ChatbotConversation.topic_label.ilike(f"%{search}%"))
    rows = (
        q.order_by(ChatbotConversation.started_at.desc(), ChatbotConversation.id.desc())
        .limit(limit)
        .all()
    )
    return [conversation_summary(c) for c in rows]


@router.get("/chatbot/conversations/{conversation_id}")
def get_conversation(
    conversation_id: int,
    business_id: int = 1,
    db: Session = Depends(get_db),
) -> dict[str, Any]:
    c = db.get(ChatbotConversation, conversation_id)
    if c is None or c.business_id != business_id:
        raise HTTPException(status_code=404, detail=f"conversation {conversation_id} not found")
    return conversation_full(c)


