@router.post("/chatbot/seed-fixtures")
def seed_fixtures(business_id: int = 1, db: Session = Depends(get_db)) -> dict[str, Any]:
    """Populate fixture conversations so the dashboard has something to show.

    Sales-rep affordance — clicking the empty-state CTA imports ~10 sample
    publisher-prospect conversations. Idempotent: re-running clears the
    existing fixture rows (external_id LIKE 'fixture-%') and re-imports.
    """
    biz = db.get(Business, business_id)
    if biz is None:
        raise HTTPException(status_code=404, detail=f"business {business_id} not found")

    # Wipe prior fixtures (external_id starts with 'fixture-').
    db.query(ChatbotConversation).filter(
        ChatbotConversation.business_id == business_id,
        ChatbotConversation.external_id.like("fixture-%"),
    ).delete(synchronize_session=False)

    now = datetime.utcnow()
    created = 0
    for idx, (topic, sentiment, escalation, reason, transcript, referrer, duration_s) in enumerate(_QUADD_FIXTURES):
        # Spread sessions across the last 14 days, most recent first.
        started_at = now - timedelta(days=idx, hours=(idx * 3) % 24, minutes=(idx * 17) % 60)
        ended_at = started_at + timedelta(seconds=duration_s)
        turns_json = [
            {"who": who, "text": text, "at": (started_at + timedelta(seconds=int(duration_s * (i + 1) / (len(transcript) + 1)))).isoformat()}
            for i, (who, text) in enumerate(transcript)
        ]
        db.add(ChatbotConversation(
            business_id=business_id,
            external_id=f"fixture-{idx + 1}",
            consumer_label=f"anonymous · {('iPhone Safari', 'desktop Chrome', 'Android Chrome', 'desktop Firefox')[idx % 4]}",
            topic_label=topic,
            transcript_json=turns_json,
            sentiment=sentiment,
            escalation_flag=escalation,
            escalation_reason=reason,
            turn_count=len(transcript),
            duration_seconds=duration_s,
            started_at=started_at,
            ended_at=ended_at,
            referrer_label=referrer,
        ))
        created += 1

    db.commit()
    return {"ok": True, "createdCount": created}


@router.delete("/chatbot/fixtures")
def clear_fixtures(business_id: int = 1, db: Session = Depends(get_db)) -> dict[str, Any]:
    """Wipe seeded fixture conversations. Real conversations untouched."""
    removed = (
        db.query(ChatbotConversation)
        .filter(
            ChatbotConversation.business_id == business_id,
            ChatbotConversation.external_id.like("fixture-%"),
        )
        .delete(synchronize_session=False)
    )
    db.commit()
    return {"ok": True, "removedCount": removed}
